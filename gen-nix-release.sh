#!/usr/bin/env bash
set -euo pipefail

# Discovers the latest Nix release, fetches hashes for all platform
# tarballs, and generates a Go source file with the results.

VERSION="${1:-}"
if [ -z "$VERSION" ]; then
  VERSION=$(curl -s https://api.github.com/repos/NixOS/nix/releases/latest | \
    grep -oP '"tag_name":\s*"\K[^"]+')
  echo "latest nix release: $VERSION" >&2
fi

PLATFORMS=(
  x86_64-linux
  aarch64-linux
  i686-linux
  armv7l-linux
  riscv64-linux
  x86_64-darwin
  aarch64-darwin
)

echo "// Code generated by gen-nix-release.sh; DO NOT EDIT."
echo ""
echo "package main"
echo ""
echo "const nixVersion = \"$VERSION\""
echo ""
echo "var nixPlatformHashes = map[string]string{"

for platform in "${PLATFORMS[@]}"; do
  url="https://releases.nixos.org/nix/nix-${VERSION}/nix-${VERSION}-${platform}.tar.xz"
  code=$(curl -s -o /dev/null -w "%{http_code}" "$url")
  if [ "$code" = "200" ]; then
    hash=$(nix-prefetch-url --type sha256 "$url" 2>/dev/null | xargs nix hash convert --from nix32 --to sri --hash-algo sha256)
    echo "	\"$platform\": \"$hash\"," >&2
    echo "	\"$platform\": \"$hash\","
  else
    echo "	// $platform: not available" >&2
  fi
done

echo "}"

# Also generate the GOARCH -> nix arch mapping from the discovered platforms
echo ""
echo "var goArchToNix = map[string]string{"
echo "	\"amd64\":   \"x86_64\","
echo "	\"arm64\":   \"aarch64\","
echo "	\"386\":     \"i686\","
echo "	\"arm\":     \"armv7l\","
echo "	\"riscv64\": \"riscv64\","
echo "}"
